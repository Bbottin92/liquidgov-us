"""What each page script does: writes out/scripts.md from the scripts themselves (read-only).
Usage: python scripts.py <assets dir> <src dir> <out dir>
For every assets/*.js: its own header comment (the author's statement of what it is for, first paragraph), the pages
that load it (route blocks or helpers whose HTML names it, from out/resolved.json, plus any C++ file that names it),
the server URLs it calls (fetch / XMLHttpRequest / sendBeacon / EventSource / WebSocket / form action / location),
the page elements it hooks (getElementById / querySelector ids and classes), and the browser events it listens to.
Nothing is executed; a script whose calls are built at run time shows only what is written literally."""
import json
import os
import re
import sys

CALL = re.compile(r"""(?:fetch|sendBeacon|EventSource|WebSocket|\.open)\s*\(\s*(?:['"]\s*[A-Z]+\s*['"]\s*,\s*)?[`'"]((?:wss?:|https?:)?/[^`'"]*)""")
NAV = re.compile(r"""(?:location(?:\.href)?\s*=|\.action\s*=|href\s*=)\s*[`'"](/[^`'"?#]*)""")
IDS = re.compile(r"""getElementById\(\s*['"]([\w-]+)['"]""")
SEL = re.compile(r"""querySelector(?:All)?\(\s*['"]([^'"]{1,60})['"]""")
EVT = re.compile(r"""addEventListener\(\s*['"](\w+)['"]""")


def header(text):
    m = re.match(r"\s*(?:/\*(.*?)\*/|((?://[^\n]*\n)+))", text, re.S)
    if not m:
        return "(no header comment)"
    body = m.group(1) if m.group(1) is not None else re.sub(r"^\s*//", "", m.group(2), flags=re.M)
    para = re.split(r"\n\s*\n", body.strip())[0]
    flat = " ".join(l.strip(" *") for l in para.splitlines())
    return flat[:600] + (" ..." if len(flat) > 600 else "")


def main(assets, src, out):
    with open(os.path.join(out, "resolved.json"), encoding="utf-8") as f:
        routes = json.load(f)
    cpp = {}
    for root, _d, files in os.walk(src):
        for fn in files:
            if fn.endswith((".cpp", ".hpp")):
                p = os.path.join(root, fn)
                cpp[os.path.relpath(p, src).replace("\\", "/")] = open(p, encoding="utf-8", errors="replace").read()
    names = sorted(f for f in os.listdir(assets) if f.endswith(".js"))
    lines = ["# Page scripts: what each one does\n",
             "Generated by scripts.py from `liquidgov-platform/assets/*.js` (%d scripts). Purpose = the script's own header "
             "comment; the rest is read from the code literally (calls built at run time are not followed).\n" % len(names)]
    for n in names:
        text = open(os.path.join(assets, n), encoding="utf-8", errors="replace").read()
        loaded_by = sorted({"%s %s" % (r["method"], r["url"]) for r in routes
                            for g in r["groups"] for o in g["objects"] if o.startswith("script ") and n in o})
        named_in = sorted(p for p, t in cpp.items() if re.search(r"[/\"']" + re.escape(n) + r"\b", t))
        calls = sorted(set(CALL.findall(text)))
        navs = sorted(set(NAV.findall(text)) - set(calls))
        ids = sorted(set(IDS.findall(text)))
        sels = sorted(set(SEL.findall(text)))
        evts = sorted(set(EVT.findall(text)))
        lines.append("## %s (%d bytes)\n" % (n, len(text.encode("utf-8"))))
        lines.append("- **Does:** %s" % header(text))
        lines.append("- **Loaded by pages:** %s" % (", ".join("`%s`" % x for x in loaded_by) or "none found in the page HTML"))
        lines.append("- **Named in server code:** %s" % (", ".join("`%s`" % x for x in named_in) or "none"))
        lines.append("- **Calls the server at:** %s" % (", ".join("`%s`" % x for x in calls) or "nothing written literally"))
        if navs:
            lines.append("- **Sends you to:** %s" % ", ".join("`%s`" % x for x in navs))
        lines.append("- **Hooks page elements:** %s" % (", ".join("#" + i for i in ids[:25]) + (" (+%d more)" % (len(ids) - 25) if len(ids) > 25 else "") or "none by id"))
        if sels:
            lines.append("- **Also selects:** %s" % ", ".join("`%s`" % s for s in sels[:15]) + (" (+%d more)" % (len(sels) - 15) if len(sels) > 15 else ""))
        lines.append("- **Listens for:** %s\n" % (", ".join(evts) or "no events"))
    with open(os.path.join(out, "scripts.md"), "w", encoding="utf-8", newline="\n") as f:
        f.write("\n".join(lines))
    print("scripts=%d written %s" % (len(names), os.path.join(out, "scripts.md")))


if __name__ == "__main__":
    main(*sys.argv[1:4])

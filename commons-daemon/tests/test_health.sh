#!/usr/bin/env bash
# GET /health reports the commit the daemon was built from: {"status":"ok","commit":"<sha>[+dirty]|unknown"}.
#   part 1  the generator (cmake/gen_build_info.cmake): where the revision comes from and in what order, and that
#           only a sha-shaped token can ever get through (it ends up inside a C string and a JSON string)
#   part 2  the real wiring: the value refreshes on `cmake --build` WITHOUT a reconfigure (the droplet deploys that
#           way and is not a git clone), an unchanged revision recompiles nothing, a changed one recompiles only
#           src/buildinfo.cpp
#   part 3  the endpoint itself, from the real binary
# In CI cmake is installed: a missing cmake there is a FAILURE, not a skip.
source "$(dirname "$0")/lib.sh"

GEN="$DAEMON_DIR/cmake/gen_build_info.cmake"
CMAKE="$(command -v cmake || true)"
if [ -z "$CMAKE" ]; then
  if [ "${CI:-}" = "true" ]; then _bad "cmake is installed in CI" "no cmake"; else echo "  skip: no cmake here (CI has it)"; fi
  exit 0
fi

echo "-- the wiring is what it should be"
CML="$DAEMON_DIR/CMakeLists.txt"
assert_contains "a custom TARGET (no OUTPUT), so it runs on every build" "$(cat "$CML")" "add_custom_target(commons_build_info"
assert_contains "the daemon depends on it" "$(cat "$CML")" "add_dependencies(commons_daemon commons_build_info)"
assert_contains "and compiles the one file that includes the generated header" "$(cat "$CML")" "src/buildinfo.cpp"
assert_eq "only src/buildinfo.cpp includes build_info.h (a new revision recompiles one file)" "src/buildinfo.cpp" "$(cd "$DAEMON_DIR" && grep -l 'build_info.h' src/*.cpp src/*.hpp | tr '\n' ' ' | sed 's/ $//')"
assert_contains "the generator rewrites the header only when it changes" "$(cat "$GEN")" "copy_if_different"
assert_contains "/health calls build_rev()" "$(grep -n 'build_rev()' "$DAEMON_DIR/src/main.cpp")" "build_rev()"

echo "-- the generator"
mkdir -p "$WORK/out"
H="$WORK/out/build_info.h"
gen() { # SRC [ENV=value ...] -> the revision in the generated header
  local src="$1"; shift
  rm -f "$H"
  env -u COMMONS_BUILD_REV "$@" "$CMAKE" -DSRC="$src" -DOUT="$H" -P "$GEN" > "$WORK/gen.log" 2>&1 || { cat "$WORK/gen.log"; return 1; }
  sed -n 's/^#define COMMONS_BUILD_REV "\(.*\)"$/\1/p' "$H"
}
S="$WORK/src"; mkdir -p "$S"
SHA40="0123456789abcdef0123456789abcdef01234567"
assert_eq "no marker, no git, no env: unknown" "unknown" "$(gen "$S")"
assert_eq "the header is exactly the documented three lines" "// generated by cmake/gen_build_info.cmake on every build; do not edit
#pragma once
#define COMMONS_BUILD_REV \"unknown\"" "$(cat "$H")"

echo "-- 1. the marker the deploy sync writes (the droplet's only source of truth)"
printf 'abc1234 2026-09-19T16:47:26Z\n' > "$S/.deployed-rev";                      assert_eq "a short sha" "abc1234" "$(gen "$S")"
printf '%s 2026-09-19T16:47:26Z\n' "$SHA40" > "$S/.deployed-rev";                   assert_eq "a full 40-char sha" "$SHA40" "$(gen "$S")"
printf '%s+dirty 2026-09-19T16:47:26Z\n' "$SHA40" > "$S/.deployed-rev";             assert_eq "a dirty-tree deploy keeps its +dirty" "$SHA40+dirty" "$(gen "$S")"
printf 'abc1234 ts\nfffffff second line\n' > "$S/.deployed-rev";                    assert_eq "only the first line counts" "abc1234" "$(gen "$S")"
printf 'abc1234\n' > "$S/.deployed-rev";                                            assert_eq "a marker with no timestamp" "abc1234" "$(gen "$S")"
echo "-- ...and only a sha-shaped token gets through (it lands in a C string and in JSON)"
n=0
for tok in "abc12" "ABCDEF1" "not-a-sha" 'abc1234"' 'abc1234";system("x");//' 'abc1234\' "abc1234;rm" "$SHA40""0" "abc1234+dirty+dirty" "abc123g" "+dirty" ""; do
  printf '%s ts\n' "$tok" > "$S/.deployed-rev"; got="$(gen "$S")"; n=$((n+1))
  assert_eq "rejected #$n ($(printf %.24s "$tok")): unknown" "unknown" "$got"
done
: > "$S/.deployed-rev";                                                             assert_eq "an empty marker" "unknown" "$(gen "$S")"
grep -q 'COMMONS_BUILD_REV "unknown"' "$H" && _ok "and the header still compiles as a C string" || _bad "the header is well-formed" "$(cat "$H")"

echo "-- 2. an explicit override beats the marker, but must be sha-shaped too"
printf 'abc1234 ts\n' > "$S/.deployed-rev"
assert_eq "COMMONS_BUILD_REV wins over the marker" "fedcba9" "$(gen "$S" COMMONS_BUILD_REV=fedcba9)"
assert_eq "an invalid override is skipped (falls through to the marker)" "abc1234" "$(gen "$S" 'COMMONS_BUILD_REV=x"; evil')"
assert_eq "an empty override is ignored" "abc1234" "$(gen "$S" COMMONS_BUILD_REV=)"
rm -f "$S/.deployed-rev"
assert_eq "an invalid override with nothing else: unknown" "unknown" "$(gen "$S" COMMONS_BUILD_REV=NOPE)"

echo "-- 3. git, when the source is in a checkout (dev and CI)"
G="$WORK/gitrepo"; mkdir -p "$G/commons-daemon"; git init -q "$G"
echo one > "$G/commons-daemon/a.txt"; echo unrelated > "$G/other.txt"
git -C "$G" add -A; git -C "$G" -c user.name=t -c user.email=t@t commit -q -m first
HEAD1="$(git -C "$G" rev-parse HEAD)"; GS="$G/commons-daemon"
assert_eq "a clean checkout reports HEAD" "$HEAD1" "$(gen "$GS")"
echo two >> "$G/commons-daemon/a.txt"
assert_eq "a modified tracked file adds +dirty" "$HEAD1+dirty" "$(gen "$GS")"
git -C "$G" checkout -q -- commons-daemon/a.txt
echo scratch > "$G/commons-daemon/untracked.txt"
assert_eq "an untracked file alone is not dirty (build products and scratch never are)" "$HEAD1" "$(gen "$GS")"
echo two >> "$G/other.txt"
assert_eq "a change outside commons-daemon/ is not this daemon's dirtiness" "$HEAD1" "$(gen "$GS")"
printf 'abc1234 ts\n' > "$GS/.deployed-rev"
assert_eq "the deploy marker beats git (on the droplet there is no git; in a checkout with a marker, the marker is the deploy)" "abc1234" "$(gen "$GS")"
assert_eq "and the override beats both" "fedcba9" "$(gen "$GS" COMMONS_BUILD_REV=fedcba9)"

echo "-- 4. the header is rewritten only when it changes"
S2="$WORK/src2"; mkdir -p "$S2"; printf 'aaaaaaa ts\n' > "$S2/.deployed-rev"
H2="$WORK/out/stable.h"; rm -f "$H2"
run_gen() { env -u COMMONS_BUILD_REV "$CMAKE" -DSRC="$S2" -DOUT="$H2" -P "$GEN" > /dev/null 2>&1; }
run_gen; t1="$(stat -c %y "$H2")"; sleep 0.05
run_gen; t2="$(stat -c %y "$H2")"
assert_eq "the same revision does not touch the header (so nothing recompiles)" "$t1" "$t2"
printf 'bbbbbbb ts\n' > "$S2/.deployed-rev"; sleep 0.05; run_gen; t3="$(stat -c %y "$H2")"
[ "$t3" != "$t2" ] && _ok "a new revision does" || _bad "a new revision rewrites the header" "$t3"
assert_contains "with the new value" "$(cat "$H2")" '"bbbbbbb"'

# ---- the real build dir, if there is one
BUILD_DIR="$(cd "$(dirname "$BIN")" 2>/dev/null && pwd)"
NEED_RESTORE=0
_hh_exit() { local rc=$?; if [ "$NEED_RESTORE" = 1 ]; then env -u COMMONS_BUILD_REV "$CMAKE" --build "$BUILD_DIR" -j2 > /dev/null 2>&1; fi; return $rc; }
trap '_hh_exit; _on_exit' EXIT
health_commit() { get "$D/health"; jget commit; }

if [ -f "$BUILD_DIR/CMakeCache.txt" ]; then
  echo "-- 5. the real wiring: the value refreshes on 'cmake --build' with NO reconfigure"
  # Precondition: bring the build directory up to date FIRST. A `git pull --rebase` (or any checkout) rewrites source mtimes, and a
  # build dir left behind them recompiles main.cpp and even reconfigures inside the assertions below, and the binary still holds an
  # older revision: that measures the directory's stale history, not the feature (found when a rebase made this test fail locally;
  # CI builds fresh and never sees it).
  env -u COMMONS_BUILD_REV "$CMAKE" --build "$BUILD_DIR" -j2 > "$WORK/prebuild.log" 2>&1 || _bad "the build directory builds" "$(tail -5 "$WORK/prebuild.log")"
  pre="$(env -u COMMONS_BUILD_REV "$CMAKE" --build "$BUILD_DIR" -j2 2>&1)"
  assert_not_contains "precondition: the build directory is up to date (a second build recompiles nothing)" "$pre" "Building CXX"
  assert_not_contains "and does not reconfigure" "$pre" "Configuring done"
  start_daemon
  R0="$(health_commit)"; stop_daemon
  [[ "$R0" =~ ^([0-9a-f]{7,40}(\+dirty)?|unknown)$ ]] && _ok "the binary under test reports a real value ($R0)" || _bad "the binary reports a valid commit" "$R0"
  NEED_RESTORE=1
  out="$(COMMONS_BUILD_REV=1234567 "$CMAKE" --build "$BUILD_DIR" -j2 2>&1)"; rc=$?
  assert_eq "an incremental build with a different revision succeeds" "0" "$rc"
  assert_not_contains "it did NOT reconfigure" "$out" "Configuring done"
  assert_contains "it recompiled buildinfo.cpp" "$out" "src/buildinfo.cpp.o"
  assert_not_contains "and nothing else (main.cpp untouched)" "$out" "src/main.cpp.o"
  assert_contains "and relinked" "$out" "Linking CXX executable"
  start_daemon; assert_eq "the running binary now reports the new revision" "1234567" "$(health_commit)"; stop_daemon
  out="$(env -u COMMONS_BUILD_REV "$CMAKE" --build "$BUILD_DIR" -j2 2>&1)"; NEED_RESTORE=0
  assert_contains "building again without the override recompiles buildinfo.cpp" "$out" "src/buildinfo.cpp.o"
  start_daemon; assert_eq "and the original revision is back" "$R0" "$(health_commit)"; stop_daemon
  out="$(env -u COMMONS_BUILD_REV "$CMAKE" --build "$BUILD_DIR" -j2 2>&1)"
  assert_not_contains "an unchanged revision recompiles NOTHING" "$out" "Building CXX"
  assert_not_contains "and relinks nothing" "$out" "Linking CXX"
else
  echo "  skip: $BUILD_DIR is not a CMake build directory (COMMONS_DAEMON_BIN points elsewhere): the refresh test needs one"
  [ "${CI:-}" = "true" ] && _bad "CI builds the daemon in a CMake build directory" "$BUILD_DIR"
fi

echo "-- 6. the endpoint, from the real binary"
start_daemon
get "$D/health"
assert_code "GET /health is 200" 200
COMMIT="$(jget commit)"
assert_eq "status is still ok (nothing that reads it breaks)" "ok" "$(jget status)"
assert_eq "the body is exactly {status, commit}" "{\"status\":\"ok\",\"commit\":\"$COMMIT\"}" "$BODY"
[[ "$COMMIT" =~ ^([0-9a-f]{7,40}(\+dirty)?|unknown)$ ]] && _ok "commit is a sha, sha+dirty or unknown: $COMMIT" || _bad "commit is well-formed" "$COMMIT"
[ -f "$BUILD_DIR/build_info.h" ] && assert_contains "it is what the generated header holds" "$(cat "$BUILD_DIR/build_info.h")" "\"$COMMIT\""
_run -i "$D/health"; assert_contains "and it is JSON" "$BODY" "Content-Type: application/json"
if [ "${CI:-}" = "true" ]; then
  assert_eq "in CI (a clean checkout) it is exactly this commit" "$(git -C "$REPO" rev-parse HEAD)" "$COMMIT"
elif [ -z "$(git -C "$REPO" status --porcelain --untracked-files=no -- commons-daemon 2>/dev/null)" ] && [ "$COMMIT" != unknown ]; then
  [ "$COMMIT" = "$(git -C "$REPO" rev-parse HEAD)" ] && _ok "on a clean tree it is this commit" || echo "  note: the binary was built from an older commit ($COMMIT); rebuild to compare"
fi
stop_daemon

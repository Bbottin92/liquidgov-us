"""Regenerate docs/site_inventory/ from one commit of the site (default: the commit live on liquidgov.us, read from
the DEPLOYED_COMMIT the last deploy recorded). Reads the code only; changes nothing on the server.
Usage: python scripts/site_inventory/update.py [<commit>]
Writes docs/site_inventory/{inventory.md,pages.md,does.md,scripts.md,audit.md}; gaps.md is hand-written and kept."""
import os
import shutil
import subprocess
import sys
import tarfile
import tempfile

HERE = os.path.dirname(os.path.abspath(__file__))
REPO = os.path.dirname(os.path.dirname(HERE))
DOCS = os.path.join(REPO, "docs", "site_inventory")


def run(*a, **kw):
    p = subprocess.run(list(a), capture_output=True, text=True, **kw)
    if p.returncode != 0:
        raise SystemExit("failed: %s\n%s" % (" ".join(a), (p.stderr or p.stdout)[-500:]))
    return p.stdout


def main():
    rev = sys.argv[1] if len(sys.argv) > 1 else "HEAD"
    sha = run("git", "-C", REPO, "rev-parse", "--short", rev).strip()
    work = tempfile.mkdtemp(prefix="site-inventory-")
    try:
        tar = os.path.join(work, "tree.tar")
        run("git", "-C", REPO, "archive", "--format=tar", "-o", tar, sha, "liquidgov-platform/src", "liquidgov-platform/assets")
        with tarfile.open(tar) as t:
            t.extractall(os.path.join(work, "tree"), filter="data")
        tools = os.path.join(work, "tools")
        shutil.copytree(HERE, tools)
        shutil.copy(os.path.join(DOCS, "gaps.md"), os.path.join(tools, "gaps.md"))
        src = os.path.join(work, "tree", "liquidgov-platform")
        out = os.path.join(tools, "out")
        print(run(sys.executable, os.path.join(tools, "inventory2.py"), os.path.join(src, "src"), out).strip())
        print(run(sys.executable, os.path.join(tools, "scripts.py"), os.path.join(src, "assets"), os.path.join(src, "src"), out).strip())
        print(run(sys.executable, os.path.join(tools, "make_index.py"), REPO, sha, "generated by scripts/site_inventory/update.py").strip())
        text = open(os.path.join(tools, "INVENTORY.md"), encoding="utf-8").read().replace("](out/", "](")
        open(os.path.join(DOCS, "inventory.md"), "w", encoding="utf-8", newline="\n").write(text)
        for f in ("pages.md", "does.md", "scripts.md", "audit.md"):
            shutil.copy(os.path.join(out, f), os.path.join(DOCS, f))
        print("docs/site_inventory updated from %s" % sha)
    finally:
        shutil.rmtree(work, ignore_errors=True)


if __name__ == "__main__":
    main()

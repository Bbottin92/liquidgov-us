"""Builds INVENTORY.md (the top-level site inventory) from out/resolved.json, out/audit.md and the hand-checked gaps.md.
Usage: python make_index.py <repo dir>      (the repo is only asked for its branch and commit)
Every count here is computed from resolved.json; nothing is typed in by hand."""
import json
import os
import subprocess
import sys

HERE = os.path.dirname(os.path.abspath(__file__))


def git(repo, *args):
    p = subprocess.run(["git", "-C", repo] + list(args), capture_output=True, text=True)
    if p.returncode != 0:
        raise SystemExit("git %s failed: %s" % (" ".join(args), p.stderr.strip()))
    return p.stdout.strip()


def area(f):
    parts = f.split("/")
    return parts[2] if len(parts) > 3 and parts[1] == "features" else "/".join(parts[:-1]) or f


def main(repo, rev="HEAD", note=""):
    for need in ("out/resolved.json", "out/audit.md", "out/pages.md", "out/does.md", "out/scripts.md", "gaps.md"):
        if not os.path.isfile(os.path.join(HERE, need)) or os.path.getsize(os.path.join(HERE, need)) == 0:
            raise SystemExit("missing or empty: " + need)
    routes = json.load(open(os.path.join(HERE, "out/resolved.json"), encoding="utf-8"))
    label = git(repo, "log", "-1", "--format=%h %ci", rev)
    dirty = git(repo, "status", "--short") if rev == "HEAD" else ""  # an exact commit read from git is never dirty
    rev = ("%s %s" % (git(repo, "rev-parse", "--abbrev-ref", "HEAD"), label) if rev == "HEAD" else
           "commit %s%s" % (label, (" (" + note + ")") if note else ""))

    pages = [r for r in routes if r["method"] in ("GET", "ANY")]
    actions = [r for r in routes if r["method"] not in ("GET", "ANY")]
    has_html = lambda r: any(g["objects"] for g in r["groups"])
    static = [r for r in pages if r.get("static")]
    read = [r for r in pages if has_html(r)]
    redirect_only = [r for r in pages if not has_html(r) and r["redirects"] and not r.get("static")]
    listed = [r for r in pages if not has_html(r) and not r["redirects"] and not r.get("static")]
    urls = {r["url"] for r in routes}

    by_area = {}
    for r in routes:
        by_area.setdefault(area(r["file"]), []).append(r)

    out = []
    w = out.append
    w("# LiquidGov site inventory\n")
    w("Source: `liquidgov-platform/src` at %s%s. Generated by `inventory2.py` + `make_index.py` from the C++ route blocks "
      "(read from git; %s).\n" % (rev, "" if not dirty else " (working tree NOT clean)",
                                  "the live server was only asked, read-only, which commit it runs" if note else
                                  "the live server was not contacted"))
    w("**Coverage:** %d routes, %d distinct URLs: %d page routes (GET/ANY) and %d action routes (POST etc.). "
      "Of the page routes, %d are static files from one table (ui/static_files.cpp), %d had their HTML read (objects "
      "listed), %d only redirect, and %d are route-listed only (HTML built where the scan cannot follow it).\n"
      % (len(routes), len(urls), len(pages), len(actions), len(static), len(read), len(redirect_only), len(listed)))
    w("Detail files: [pages.md](out/pages.md) (every URL: groups and objects, nested), [does.md](out/does.md) "
      "(every form, button and script on each page), [scripts.md](out/scripts.md) (what each page script does, what it "
      "calls, which pages load it), [audit.md](out/audit.md) (raw link audit), resolved.json (all of it).\n")

    w("## Pages and actions by area\n")
    w("Access is read from each route's own gate (`if(!acc) return need_login();` = members, `is_operator(user)` = "
      "operators); the router has no global gate (router.cpp:85-107).\n")
    w("| Area | Pages (GET) | Actions (POST etc.) | Public | Members only | Operators only |\n|---|---|---|---|---|---|")
    for a in sorted(by_area):
        rs = by_area[a]
        w("| %s | %d | %d | %d | %d | %d |" % (a, sum(r["method"] in ("GET", "ANY") for r in rs),
                                               sum(r["method"] not in ("GET", "ANY") for r in rs),
                                               *[sum(r["access"] == k for r in rs) for k in ("public", "members", "operators")]))
    w("")
    for a in sorted(by_area):
        w("### %s\n" % a)
        for r in sorted(by_area[a], key=lambda r: (r["url"], r["method"])):
            objs = sum(len(g["objects"]) for g in r["groups"])
            note = "static file (table row)" if r.get("static") else "%d objects in %d groups" % (objs, len(r["groups"])) if objs else (
                "redirects to " + r["redirects"][0][:60] if r["redirects"] else
                ("reads " + ", ".join(r["reads"][:6]) if r["reads"] else "no HTML found"))
            w("- `%s %s` (`%s:%d`) - %s%s" % (r["method"], r["url"], r["file"], r["line"], note,
                                             "" if r["access"] == "public" else " - **%s only**" % r["access"]))
        w("")

    w("## Pages whose HTML was not read (route-listed only)\n")
    for r in sorted(listed, key=lambda r: r["url"]):
        w("- `%s` (`%s:%d`)%s" % (r["url"], r["file"], r["line"],
                                  " - builds via " + ", ".join(r["unresolved_helpers"]) if r["unresolved_helpers"] else ""))
    w("")
    w(open(os.path.join(HERE, "gaps.md"), encoding="utf-8").read())
    path = os.path.join(HERE, "INVENTORY.md")
    with open(path, "w", encoding="utf-8", newline="\n") as f:
        f.write("\n".join(out))
    print("wrote %s (%d bytes): routes=%d urls=%d pages=%d read=%d redirect_only=%d listed=%d actions=%d areas=%d"
          % (path, os.path.getsize(path), len(routes), len(urls), len(pages), len(read), len(redirect_only), len(listed), len(actions), len(by_area)))


if __name__ == "__main__":
    main(*sys.argv[1:4])
